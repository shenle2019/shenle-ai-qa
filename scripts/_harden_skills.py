def strip_old(body: str) -> str:
    if MARK in body:
        body = body.split(MARK)[0].rstrip() + "\n"
    return body


def fix_description(text: str, desc: str) -> str:
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if line.startswith("description:"):
            lines[i] = f'description: "{desc}"'
            break
    return "\n".join(lines)


def build(name: str) -> None:
    path = SKILLS / name / "SKILL.md"
    text = path.read_text(encoding="utf-8")
    text = fix_description(text, DESC[name])
    head, sep, body = text.partition("\n---\n")
    body = strip_old(body)
    b = BLOCKS[name]
    tail = f"""
{MARK}
## 执行顺序

{b["order"]}
## 判断与选择

{b["judge"]}
## 反模式

{b["anti"]}
## 失败兜底

{b["fallback"]}
## 一页速查

{b["cheat"]}
## 示例

{b["example"]}"""
    path.write_text(head + sep + body.rstrip() + "\n" + tail, encoding="utf-8")
    print(f"{name:34s} {len((body + tail).splitlines()):4d} lines")


def main() -> None:
    for name in BLOCKS:
        build(name)


if __name__ == "__main__":
    main()
